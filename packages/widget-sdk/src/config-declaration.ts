import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { parseSettingsSchema, type SettingsSchema } from '@lifedashboard/contracts/widget-settings'

export const CONFIG_DECLARATION_FILE = 'widget-env.d.ts'

export function renderConfigDeclaration(settings: SettingsSchema | undefined): string {
  const properties = Object.entries(settings?.properties ?? {}).map(([key, setting]) => {
    const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${JSON.stringify(key).slice(1, -1).replace(/'/g, "\\'")}'`
    const description = setting.description === undefined ? setting.title : `${setting.title} — ${setting.description}`
    const comment = (description + (setting.type === 'secret'
      ? '. True when the user has set it; the widget never gets the value.' : '')).replace(/\*\//g, '*\\/')
    const type = setting.type === 'secret' || setting.type === 'boolean' ? 'boolean'
      : setting.type === 'integer' || setting.type === 'number' ? 'number'
        : setting.enum === undefined ? 'string' : setting.enum.map((value) => JSON.stringify(value)).join(' | ')
    return `    /** ${comment} */\n    ${name}: ${type}`
  })
  const body = properties.length === 0 ? '{}' : `{\n${properties.join('\n')}\n  }`
  return `// Generated by ld-widget from widget.json. Do not edit: dev, check and build rewrite it.
import '@lifedashboard/widget-sdk'

declare module '@lifedashboard/widget-sdk' {
  interface WidgetConfig ${body}
}
`
}

export async function writeConfigDeclaration(dir: string): Promise<void> {
  const raw = JSON.parse(await readFile(join(dir, 'widget.json'), 'utf8')) as { settings?: unknown; network?: string[] }
  let settings: SettingsSchema | undefined
  if (raw.settings !== undefined) {
    const parsed = parseSettingsSchema(raw.settings, raw.network ?? [])
    if (!parsed.ok) throw new Error(`Invalid widget.json: ${parsed.error}`)
    settings = parsed.value
  }
  const content = renderConfigDeclaration(settings)
  const path = join(dir, CONFIG_DECLARATION_FILE)
  try {
    if (await readFile(path, 'utf8') === content) return
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
  }
  await writeFile(path, content)
}
