import { spawnSync } from 'node:child_process'
import { cp, mkdir, mkdtemp, readFile, rm, stat, utimes, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { SettingsSchema } from '@lifedashboard/contracts/widget-settings'
import { afterEach, expect, it } from 'vitest'
import { buildWidget } from '../src/build.ts'
import { CONFIG_DECLARATION_FILE, renderConfigDeclaration, writeConfigDeclaration } from '../src/config-declaration.ts'

const dirs: string[] = []
const settings: SettingsSchema = { type: 'object', properties: {
  city: { type: 'string', title: 'Город', description: 'Где */ смотреть', default: 'Москва' },
  count: { type: 'integer', title: 'Сколько', default: 3 },
  ratio: { type: 'number', title: 'Доля', default: 0.5 },
  on: { type: 'boolean', title: 'Вкл', default: true },
  mode: { type: 'string', title: 'Режим', enum: ['a', "b'c", 'd\ne'], default: 'a' },
  '1st': { type: 'string', title: 'Первый', default: '' },
  apiKey: { type: 'secret', title: 'Ключ', bind: { origin: 'https://api.example.com', header: 'Authorization' } },
} }

const emptyDeclaration = `// Generated by ld-widget from widget.json. Do not edit: dev, check and build rewrite it.
import '@lifedashboard/widget-sdk'

declare module '@lifedashboard/widget-sdk' {
  interface WidgetConfig {}
}
`

async function project(manifest: Record<string, unknown> = {}): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), 'ld-widget-config-test-'))
  dirs.push(dir)
  await writeFile(join(dir, 'widget.json'), JSON.stringify(manifest))
  return dir
}

afterEach(async () => {
  await Promise.all(dirs.splice(0).map((dir) => rm(dir, { recursive: true, force: true })))
})

it('renders every setting type, quoting keys that are not identifiers', () => {
  expect(renderConfigDeclaration(settings)).toBe(`// Generated by ld-widget from widget.json. Do not edit: dev, check and build rewrite it.
import '@lifedashboard/widget-sdk'

declare module '@lifedashboard/widget-sdk' {
  interface WidgetConfig {
    /** Город — Где *\\/ смотреть */
    city: string
    /** Сколько */
    count: number
    /** Доля */
    ratio: number
    /** Вкл */
    on: boolean
    /** Режим */
    mode: "a" | "b'c" | "d\\ne"
    /** Первый */
    '1st': string
    /** Ключ. True when the user has set it; the widget never gets the value. */
    apiKey: boolean
  }
}
`)
})

it('renders an empty interface without settings', () => {
  expect(renderConfigDeclaration(undefined)).toBe(emptyDeclaration)
})

it('writes widget-env.d.ts in a temp project without settings', async () => {
  const dir = await project()
  expect(CONFIG_DECLARATION_FILE).toBe('widget-env.d.ts')
  await writeConfigDeclaration(dir)
  expect(await readFile(join(dir, CONFIG_DECLARATION_FILE), 'utf8')).toBe(emptyDeclaration)
})

it('parses settings against manifest.network and updates a changed declaration', async () => {
  const dir = await project()
  await writeConfigDeclaration(dir)
  const schema: SettingsSchema = { type: 'object', properties: { apiKey: settings.properties.apiKey! } }
  await writeFile(join(dir, 'widget.json'), JSON.stringify({ settings: schema, network: ['https://api.example.com'] }))
  await writeConfigDeclaration(dir)
  expect(await readFile(join(dir, CONFIG_DECLARATION_FILE), 'utf8')).toBe(renderConfigDeclaration(schema))
})

it('leaves the file mtime unchanged when its content has not changed', async () => {
  const dir = await project()
  await writeConfigDeclaration(dir)
  const path = join(dir, CONFIG_DECLARATION_FILE)
  await utimes(path, new Date('2000-01-01'), new Date('2000-01-01'))
  const before = (await stat(path)).mtimeMs
  await writeConfigDeclaration(dir)
  expect((await stat(path)).mtimeMs).toBe(before)
})

it.each([
  { settings: null },
  { settings: { type: 'array' } },
  { settings: { type: 'object', properties: { apiKey: settings.properties.apiKey } } },
])('rejects invalid settings in %j', async (manifest) => {
  const dir = await project(manifest)
  await expect(writeConfigDeclaration(dir)).rejects.toThrow(/^Invalid widget.json: settings/)
})

it('leaves widget-env.d.ts in the project after building a counter copy', async () => {
  const dir = await project()
  await cp(fileURLToPath(new URL('./fixtures/counter/', import.meta.url)), dir, { recursive: true })
  await buildWidget(dir)
  expect(await readFile(join(dir, CONFIG_DECLARATION_FILE), 'utf8')).toBe(emptyDeclaration)
}, 30_000)

it('compiles the generated declaration and typed read-only config with workspace tsc', async () => {
  const dir = await project()
  await mkdir(join(dir, 'src'))
  await writeFile(join(dir, CONFIG_DECLARATION_FILE), renderConfigDeclaration(settings))
  await writeFile(join(dir, 'package.json'), JSON.stringify({ type: 'module' }))
  await writeFile(join(dir, 'tsconfig.json'), JSON.stringify({
    compilerOptions: {
      target: 'es2024', module: 'nodenext', moduleResolution: 'nodenext',
      strict: true, noEmit: true, allowImportingTsExtensions: true,
      paths: { '@lifedashboard/widget-sdk': [fileURLToPath(new URL('../src/index.ts', import.meta.url))] },
    },
    include: ['src/main.ts', 'widget-env.d.ts'],
  }))
  await writeFile(join(dir, 'src', 'main.ts'), `import { useWidget, type WidgetConfig } from '@lifedashboard/widget-sdk'
const { config } = useWidget().context
const mode: 'a' | "b'c" | 'd\\ne' = config.mode
const city: string = config.city
const count: number = config.count
const ratio: number = config.ratio
const on: boolean = config.on
const first: string = config['1st']
const apiKey: boolean = config.apiKey
const declaredMode: WidgetConfig['mode'] = mode
// @ts-expect-error Config values are read-only.
config.mode = 'a'
// @ts-expect-error Only declared settings are available.
config.missing
// @ts-expect-error Enum values retain their literal types.
const invalid: typeof mode = 'other'
`)
  const result = spawnSync(process.execPath, [
    fileURLToPath(new URL('../node_modules/typescript/bin/tsc', import.meta.url)), '--noEmit', '-p', dir,
  ], { encoding: 'utf8', timeout: 30_000 })
  expect(result.error).toBeUndefined()
  expect(result.stdout).toBe('')
  expect(result.stderr).toBe('')
  expect(result.status).toBe(0)
}, 30_000)
